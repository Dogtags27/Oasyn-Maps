/**
 * gen-fixtures.mjs — regenerate contract fixtures from the LIVE engine (task 30,
 * R13.8, R17.5).
 *
 * Mock mode (the stub server + the frontend's offline development) must stay
 * close to live, so we drive the real pipeline with canonical requests and write
 * each endpoint's actual response as a `kind: "sample"` fixture. The geometry is
 * real inner-metro coordinates; resource names come straight from the snapshot
 * layers. After writing, re-run `npm test` so contract.test.ts re-validates.
 *
 * Endpoints that don't need the graph (body, escalation) are generated from
 * their pure cores; config/meta/presets/layers are left as curated fixtures
 * (config/meta are generated by their routes at runtime; presets are seed data).
 *
 * Run: tsx scripts/gen-fixtures.mjs   (needs R2 creds in .env)
 */

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

import { loadSnapshot } from "../src/snapshot.js";
import { buildGraphView } from "../src/core/graph.js";
import { plan } from "../src/core/plan.js";
import { backwardTree, remainingRoute, hasHardUnsafeEdge } from "../src/core/rerouting.js";
import { resolveEnv, buildHeatArray, heatMin } from "../src/core/env.js";
import { buildSafetyArray } from "../src/core/safety.js";
import { personalFactor, minCostPerMetre, edgeTime } from "../src/core/cost.js";
import { initA0, aTrace, band } from "../src/core/exposure.js";
import { tcModel, tcRange, tcUsed, pfUplift } from "../src/core/body.js";
import { step as escStep } from "../src/core/escalation.js";
import { oasisCoverage, suggestSites } from "../src/core/coverage.js";
import { departureCurve } from "../src/core/departure.js";
import { loadResources } from "../src/routes/resources.js";
import { d } from "../src/core/descriptors.js";
import { body as bodyCfg } from "../src/config.js";

const here = dirname(fileURLToPath(import.meta.url));
const fixturesDir = join(here, "..", "contract", "fixtures");

const BACK_BAY = { lat: 42.348, lng: -71.081 };
const NEU = { lat: 42.3398, lng: -71.0892 };
const SCENARIO = {
  timeISO: "2026-07-21T14:00:00-04:00",
  tempC: 36, rh: 45, cloud: 0.1, radiation: undefined,
  priorWalkMin: 15, hr: 88, stepFree: false, zones: [], liveWeather: false,
};
const resolved = {
  timeMs: Date.parse(SCENARIO.timeISO),
  tempC: SCENARIO.tempC, rh: SCENARIO.rh, cloud: SCENARIO.cloud,
  priorWalkMin: SCENARIO.priorWalkMin, hr: SCENARIO.hr, stepFree: SCENARIO.stepFree,
};

const write = (name, endpoint, response) => {
  const payload = { kind: "sample", endpoint, generated: "from-live-engine", response };
  writeFileSync(join(fixturesDir, `${name}.json`), JSON.stringify(payload, null, 2) + "\n");
  console.log(`  wrote ${name}.json`);
};

function serialiseRoute(snap, r, mode, j, feasible, turns, explanations, A0) {
  const dts = [], hs = [], lens = [];
  for (const e of r.edges) {
    dts.push(edgeTime(snap.len[e], snap.step[e] === 1));
    hs.push(snap.heat[e]);
    lens.push(snap.len[e]);
  }
  return {
    id: `route-${r.edges.length}-${Math.round(r.timeSec)}-${Math.round(r.x * 1000)}`,
    mode,
    geometry: r.nodes.map((n) => ({ lat: snap.nodeLat[n], lng: snap.nodeLon[n] })),
    timeSec: r.timeSec, distanceM: r.distanceM, heatMinutes: r.heatMinutes,
    shadePct: r.shadeFrac * 100, arrivalBand: band(r.aEnd), safetyMax: r.safetyMax,
    oases: [], j, feasible, turns, aTrace: aTrace(A0, dts, hs, lens), explanations,
  };
}

async function main() {
  const snap = await loadSnapshot();
  const graph = buildGraphView(snap);
  console.log(`snapshot: ${snap.V} nodes, ${snap.E} edges`);

  const env = resolveEnv(resolved, snap.center);
  buildHeatArray(snap, env);
  buildSafetyArray(snap, [], snap.center);
  const A0 = initA0(heatMin(env.theta, env.I), resolved.priorWalkMin);

  // --- plan ----------------------------------------------------------------
  const out = plan({ snap, graph, scenario: resolved, zones: [], mode: "balanced", from: BACK_BAY, to: NEU });
  const rec = out.recommended;
  const routes = out.routes.map((s) => {
    const isRec = s.route === rec;
    return serialiseRoute(
      snap, s.route, "balanced", s.j, s.feasible,
      isRec ? (out.turnsByRoute.get(s.route) ?? []) : [],
      isRec ? out.explanations : [], A0,
    );
  });
  const recommendedId = routes.find((_, i) => out.routes[i].route === rec)?.id ?? null;
  write("plan", "POST /api/plan", { routes, recommendedId, offers: out.offers ?? [] });

  // --- replan --------------------------------------------------------------
  const ctx = {
    snap, graph, scenario: resolved, env,
    heat: snap.heat, safety: snap.safety,
    pf: personalFactor({ A0, hr: resolved.hr, hrBase: bodyCfg.HR_base }),
    cMin: 0, mode: "balanced",
  };
  ctx.cMin = minCostPerMetre(ctx);
  const goalNode = graph.snapNode(NEU.lat, NEU.lng);
  const midNode = graph.snapNode(42.344, -71.0855);
  const tree = backwardTree(ctx, goalNode);
  const remaining = remainingRoute(ctx, tree, midNode, A0);
  const remRoute = remaining ? serialiseRoute(snap, remaining, "balanced", 0, true, [], [], A0) : null;
  write("replan", "POST /api/replan", {
    remaining: remRoute,
    offers: remaining && hasHardUnsafeEdge(ctx, remaining)
      ? [{ kind: "safety", deltaTimeSec: 0, deltaHeatMinutes: 0, deltaJ: 0, trigger: d("offer.safety.trigger"), expiryMs: resolved.timeMs + 300000, snoozeKey: "safety", priority: "high" }]
      : [],
  });

  // --- body ----------------------------------------------------------------
  const model = tcModel(0.5, 100);
  const used = tcUsed({ model, obs: 38.6, wearableOn: true });
  const range = tcRange(used);
  write("body", "POST /api/body", {
    tcModel: model, tcUsed: used, rangeLow: range.low, rangeHigh: range.high,
    band: band(0.5), pfUplift: pfUplift(38.6, model).factor,
    label: d("body.label.simulatedWearable"), simulated: true,
  });

  // --- escalation ----------------------------------------------------------
  const next = escStep({ phase: "caution" }, 39.2, resolved.timeMs, "none");
  write("escalation", "POST /api/escalation/step", { state: next, simulated: true });

  // --- coverage ------------------------------------------------------------
  const resources = await loadResources(snap, graph);
  const oasisNodes = resources.map((r) => r.node);
  const cov = oasisCoverage(ctx, oasisNodes);
  const sug = suggestSites(ctx, oasisNodes, 2);
  const stride = Math.max(1, Math.floor(snap.V / 50));
  const samples = [];
  for (let i = 0; i < snap.V && samples.length < 50; i += stride) {
    if (!Number.isFinite(cov.dMin[i])) continue;
    samples.push({ at: { lat: snap.nodeLat[i], lng: snap.nodeLon[i] }, minutes: cov.dMin[i] / 60 });
  }
  write("coverage", "POST /api/coverage", {
    within5Pct: cov.within5 * 100, within10Pct: cov.within10 * 100, samples,
    suggestions: sug.map((s, i) => ({ at: { lat: snap.nodeLat[s.node], lng: snap.nodeLon[s.node] }, label: d("coverage.suggestion", { rank: i + 1 }), benefit: s.benefit })),
    heuristicNote: d("coverage.heuristicNote"),
  });

  // --- departure -----------------------------------------------------------
  const curve = departureCurve({
    snap, graph, baseScenario: resolved, safety: snap.safety, mode: "balanced",
    from: graph.snapNode(BACK_BAY.lat, BACK_BAY.lng), to: goalNode, samples: 8,
  });
  write("departure", "POST /api/departure", {
    points: curve.points.map((p) => ({ tISO: new Date(p.timeMs).toISOString(), heatMin: p.heatMin })),
    best: { tISO: new Date(curve.best.timeMs).toISOString(), reductionPct: curve.best.reductionPct },
  });

  console.log("done. Re-run `npm test` to re-validate the contract.");
}

main().catch((err) => {
  console.error("gen-fixtures failed:", err.message);
  process.exitCode = 1;
});
